# Execute the actual generated post-install block against boundary fixtures,
# then verify the real CocoaPods project. No build settings are changed here.
require 'xcodeproj'

def check(condition, message)
  raise message unless condition
end

podfile, project_path = ARGV
check(podfile && project_path, 'Expected generated Podfile and Pods.xcodeproj')
contents = File.read(podfile)
block = contents[/# @generated by with-livekit-ios-static-framework-compatibility - start\n(.*?)# @generated by with-livekit-ios-static-framework-compatibility - end/m, 1]
check(block, 'Missing generated LiveKit compatibility block')
allowed = %w[livekit-react-native-webrtc livekit_react_native_webrtc livekit-react-native livekit_react_native ChillywoodCameraEffects]
flag = '-Wno-non-modular-include-in-framework-module'
configuration = Struct.new(:build_settings)
target = Struct.new(:name, :build_configurations)
project = Struct.new(:targets)
installer_type = Struct.new(:pods_project)
fixtures = [nil, '-DCUSTOM=1 -DNAME="two words"', ['$(inherited)', '-DCUSTOM=1'], "$(inherited) #{flag}"]
targets = (allowed + %w[ExpoModulesCore React-Core Chillywood OtherPod ChillywoodCameraEffectsExtra]).map do |name|
  target.new(name, fixtures.map { |value| configuration.new({ 'OTHER_CFLAGS' => value&.dup, 'OTHER_SWIFT_FLAGS' => '-DKEEP_SWIFT' }) })
end
snapshot = -> { targets.map { |item| item.build_configurations.map(&:build_settings) } }
before = Marshal.load(Marshal.dump(snapshot.call))
installer = installer_type.new(project.new(targets))
eval(block, binding, podfile)
once = Marshal.dump(snapshot.call)
eval(block, binding, podfile)
check(once == Marshal.dump(snapshot.call), 'Repeated post-install must be idempotent')
targets.each_with_index do |item, index|
  item.build_configurations.each_with_index do |config, config_index|
    previous = before[index][config_index]
    settings = config.build_settings
    unless allowed.include?(item.name)
      check(settings == previous, "Unexpected change to #{item.name}")
      next
    end
    check(settings['CLANG_ALLOW_NON_MODULAR_INCLUDES_IN_FRAMEWORK_MODULES'] == 'YES', 'Missing narrow module compatibility')
    flags = settings['OTHER_CFLAGS']
    text = flags.is_a?(Array) ? flags.join(' ') : flags
    check(text.include?('$(inherited)') && text.scan(flag).length == 1, 'Must retain inherited flags and one compatibility flag')
    prior_flags = previous['OTHER_CFLAGS']
    check(prior_flags.nil? || (prior_flags.is_a?(Array) ? (prior_flags - flags).empty? : text.include?(prior_flags)), 'Existing flags were lost')
    check(settings['OTHER_SWIFT_FLAGS'] == previous['OTHER_SWIFT_FLAGS'], 'Swift flags changed')
  end
end

pods = Xcodeproj::Project.open(project_path)
camera = pods.targets.find { |item| item.name == 'ChillywoodCameraEffects' }
check(camera, 'Actual camera Pod target is missing')
camera.build_configurations.each do |config|
  settings = config.build_settings
  check(settings['CLANG_ALLOW_NON_MODULAR_INCLUDES_IN_FRAMEWORK_MODULES'] == 'YES', "#{config.name}: missing camera compatibility setting")
  check(Array(settings['OTHER_CFLAGS']).join(' ').include?(flag), "#{config.name}: missing camera importer flag")
  check(settings['CLANG_ENABLE_MODULES'] != 'NO', 'Camera modules must remain enabled')
  check(settings['GCC_WARN_INHIBIT_ALL_WARNINGS'] != 'YES', 'Camera warnings must not be globally inhibited')
end
puts 'iOS: generated Ruby fixtures and actual camera Pod build settings passed; full native compile still required'
