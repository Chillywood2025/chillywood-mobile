#!/usr/bin/env node

import { readFileSync } from "node:fs";
import path from "node:path";

const root = process.cwd();
const appDir = path.join(root, "assets/sounds/chilly-chat");
const androidDir = path.join(root, "android/app/src/main/res/raw");

const expected = [
  "chilly_ring.wav",
  "skyline_pulse.wav",
  "theater_bell.wav",
  "velvet_knock.wav",
  "quiet_buzz.wav",
  "classic_phone.wav",
];

const failures = [];
const fail = (message) => failures.push(message);
const assert = (condition, message) => {
  if (!condition) fail(message);
};

const read = (relativePath) => readFileSync(path.join(root, relativePath), "utf8");

const parseWav = (buffer, file) => {
  assert(buffer.toString("ascii", 0, 4) === "RIFF", `${file} must be RIFF WAV`);
  assert(buffer.toString("ascii", 8, 12) === "WAVE", `${file} must be WAVE`);
  const channels = buffer.readUInt16LE(22);
  const sampleRate = buffer.readUInt32LE(24);
  const bits = buffer.readUInt16LE(34);
  const dataOffset = buffer.indexOf(Buffer.from("data"));
  assert(dataOffset > 0, `${file} must contain a data chunk`);
  const dataSize = buffer.readUInt32LE(dataOffset + 4);
  const sampleCount = dataSize / 2;
  let peak = 0;
  let sumSquares = 0;
  for (let offset = dataOffset + 8; offset < dataOffset + 8 + dataSize; offset += 2) {
    const value = buffer.readInt16LE(offset) / 32768;
    peak = Math.max(peak, Math.abs(value));
    sumSquares += value * value;
  }
  return {
    bits,
    channels,
    duration: sampleCount / sampleRate,
    peak,
    rms: Math.sqrt(sumSquares / sampleCount),
    sampleRate,
  };
};

for (const file of expected) {
  const appBuffer = readFileSync(path.join(appDir, file));
  const androidBuffer = readFileSync(path.join(androidDir, file));
  assert(Buffer.compare(appBuffer, androidBuffer) === 0, `${file} app asset and Android raw copy must match exactly`);
  const stats = parseWav(appBuffer, file);
  assert(stats.channels === 1, `${file} must be mono`);
  assert(stats.sampleRate === 44_100, `${file} must be 44100 Hz`);
  assert(stats.bits === 16, `${file} must be 16-bit PCM`);
  assert(stats.duration >= 2.4, `${file} must be long enough to behave like a ringtone, not a click`);
  assert(stats.duration <= 4.0, `${file} must remain compact for mobile bundling`);
  assert(stats.peak >= 0.55, `${file} must be audibly normalized`);
  assert(stats.rms >= (file === "quiet_buzz.wav" ? 0.12 : 0.16), `${file} must not be a weak click-only asset`);
}

const soundAssets = read("_lib/chillyChatCallSoundAssets.ts");
const calls = read("_lib/chillyChatCalls.ts");
const licenses = read("docs/CHILLY_CHAT_SOUND_LICENSES.md");
const generator = read("scripts/generate-chilly-chat-modern-ringtones.mjs");

expected.forEach((file) => {
  const key = file.replace(".wav", "");
  assert(soundAssets.includes(file), `${file} must remain mapped in call sound assets`);
  assert(calls.includes(key), `${key} preference key must remain supported`);
  assert(licenses.includes(file), `${file} must have provenance documentation`);
  assert(generator.includes(file), `${file} must be generated by the deterministic asset script`);
});

assert(licenses.includes("original generated Chi'llywood app assets"), "sound license doc must identify the new assets as original/generated");
assert(licenses.includes("No third-party ringtone files are used"), "sound license doc must say no third-party ringtone files are used");
assert(soundAssets.includes('CHILLY_CHAT_DEFAULT_NOTIFICATION_SOUND = "chilly_ring.wav"'), "background call channel must keep Chi'lly Ring as the default bundled sound");
assert(calls.includes("Silent / Vibrate Only"), "silent/vibrate preference must remain compatible");

if (failures.length) {
  console.error("Chi'lly Chat ringtone asset guard failed:");
  failures.forEach((failure) => console.error(`- ${failure}`));
  process.exit(1);
}

console.log("Chi'lly Chat ringtone asset guard passed.");
